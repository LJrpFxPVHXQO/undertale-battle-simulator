"""Convert the game over halves into CHR tiles (4KB bank 63) and a nametable include.

usage: python py/gameover_img.py   (run from the repo root)
"""
from PIL import Image

CHR = "Undertale.chr"
OUT = "asm/dodge/gameover_img.inc"
LEFT = "data/monsters/game_over_left.png"
RIGHT = "data/monsters/game_over_right.png"
BANK = 63
SCALE = 0.4
POS_X, POS_Y = 44, 32

def load(path):
    im = Image.open(path).convert("L")
    size = (round(im.width * SCALE), round(im.height * SCALE))
    return im.resize(size, Image.BOX).point(lambda v: 255 if v > 110 else 0)

left, right = load(LEFT), load(RIGHT)
canvas = Image.new("L", (256, 240), 0)
canvas.paste(left, (POS_X, POS_Y))
canvas.paste(right, (POS_X + left.width, POS_Y))

first_row = POS_Y // 8
last_row = (POS_Y + max(left.height, right.height) - 1) // 8

tiles = [bytes(8)]
rows = []
for ty in range(first_row, last_row + 1):
    row = []
    for tx in range(32):
        t = canvas.crop((tx * 8, ty * 8, tx * 8 + 8, ty * 8 + 8))
        pat = bytes(
            sum(1 << (7 - x) for x in range(8) if t.getpixel((x, y))) for y in range(8)
        )
        if pat not in tiles:
            tiles.append(pat)
        row.append(tiles.index(pat))
    rows.append(row)
assert len(tiles) <= 256

chr_data = bytearray(open(CHR, "rb").read())
base = BANK * 4096
chr_data[base:base + 4096] = bytes(4096)
for i, pat in enumerate(tiles):
    chr_data[base + i * 16:base + i * 16 + 16] = pat + pat
open(CHR, "wb").write(chr_data)

with open(OUT, "w") as f:
    f.write("; generated by py/gameover_img.py\n")
    f.write("GAMEOVER_ROWS = %d\n" % len(rows))
    f.write("GAMEOVER_FIRST_ROW = %d\n" % first_row)
    f.write("gameover_nt:\n")
    for row in rows:
        f.write("    .byte " + ", ".join(str(v) for v in row) + "\n")
canvas.resize((512, 480), Image.NEAREST).save("gameover_preview.png")
print(len(tiles), "tiles", len(rows), "rows from", first_row)
