"""Convert the SOUL DODGE title halves into CHR tiles (4KB bank 62) and a nametable include.

usage: python py/landing_logo.py   (run from the repo root, after the CHR is built)
"""
from PIL import Image

CHR = "Undertale.chr"
OUT = "asm/dodge/landing_logo.inc"
LEFT = "data/monsters/soul_dodge_left.png"
RIGHT = "data/monsters/soul_dodge_right.png"
BANK = 62
HALF_W = 124
POS_X, POS_Y = 4, 48


def load(path):
    im = Image.open(path).convert("RGB")
    h = round(im.height * HALF_W / im.width)
    return im.resize((HALF_W, h), Image.BOX)


def classify(p):
    r, g, b = p
    if r > 150 and g < 110 and b < 110:
        return 1  # red heart
    return 3 if r + g + b > 380 else 0


left, right = load(LEFT), load(RIGHT)
canvas = Image.new("L", (256, 240), 0)
for im, x0 in ((left, POS_X), (right, POS_X + HALF_W)):
    for y in range(im.height):
        for x in range(im.width):
            canvas.putpixel((x0 + x, POS_Y + y), classify(im.getpixel((x, y))))

first_row = POS_Y // 8
last_row = (POS_Y + max(left.height, right.height) - 1) // 8

tiles = [bytes(16)]
rows = []
for ty in range(first_row, last_row + 1):
    row = []
    for tx in range(32):
        t = canvas.crop((tx * 8, ty * 8, tx * 8 + 8, ty * 8 + 8))
        p0, p1 = [], []
        for y in range(8):
            a = b = 0
            for x in range(8):
                v = t.getpixel((x, y))
                a |= (v & 1) << (7 - x)
                b |= ((v >> 1) & 1) << (7 - x)
            p0.append(a)
            p1.append(b)
        pat = bytes(p0 + p1)
        if pat not in tiles:
            tiles.append(pat)
        row.append(tiles.index(pat))
    rows.append(row)
assert len(tiles) <= 256 and len(rows) * 32 <= 256

chr_data = bytearray(open(CHR, "rb").read())
base = BANK * 4096
chr_data[base:base + 4096] = bytes(4096)
for i, pat in enumerate(tiles):
    chr_data[base + i * 16:base + i * 16 + 16] = pat
open(CHR, "wb").write(chr_data)

with open(OUT, "w") as f:
    f.write("; generated by py/landing_logo.py\n")
    f.write("LOGO_ROWS = %d\n" % len(rows))
    f.write("LOGO_FIRST_ROW = %d\n" % first_row)
    f.write("logo_nt:\n")
    for row in rows:
        f.write("    .byte " + ", ".join(str(v) for v in row) + "\n")
print(len(tiles), "tiles", len(rows), "rows from", first_row)
