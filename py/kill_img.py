"""Convert froggit_kill.png into CHR tiles (4KB bank 60) and a nametable include.

usage: python py/kill_img.py   (run from the repo root, after the CHR is built)
"""
from PIL import Image

CHR = "Undertale.chr"
OUT = "asm/dodge/kill_img.inc"
SRC = "data/monsters/froggit/froggit_kill.png"
BANK = 60

im = Image.open(SRC).convert("RGBA")
bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
bg.alpha_composite(im)
im = bg.convert("L").point(lambda v: 255 if v > 110 else 0)
im = im.crop(im.getbbox())

pos_x = (256 - im.width) // 2
pos_y = (240 - im.height) // 2
canvas = Image.new("L", (256, 240), 0)
canvas.paste(im, (pos_x, pos_y))

first_row = pos_y // 8
last_row = (pos_y + im.height - 1) // 8

tiles = [bytes(8)]
rows = []
for ty in range(first_row, last_row + 1):
    row = []
    for tx in range(32):
        t = canvas.crop((tx * 8, ty * 8, tx * 8 + 8, ty * 8 + 8))
        pat = bytes(
            sum(1 << (7 - x) for x in range(8) if t.getpixel((x, y))) for y in range(8)
        )
        if pat not in tiles:
            tiles.append(pat)
        row.append(tiles.index(pat))
    rows.append(row)
assert len(tiles) <= 256, len(tiles)
assert len(rows) * 32 <= 512

chr_data = bytearray(open(CHR, "rb").read())
base = BANK * 4096
chr_data[base:base + 4096] = bytes(4096)
for i, pat in enumerate(tiles):
    chr_data[base + i * 16:base + i * 16 + 16] = pat + pat
open(CHR, "wb").write(chr_data)

with open(OUT, "w") as f:
    f.write("; generated by py/kill_img.py\n")
    f.write("KILL_ROWS = %d\n" % len(rows))
    f.write("KILL_FIRST_ROW = %d\n" % first_row)
    f.write("kill_nt:\n")
    for row in rows:
        f.write("    .byte " + ", ".join(str(v) for v in row) + "\n")
print(len(tiles), "tiles", len(rows), "rows from", first_row)

