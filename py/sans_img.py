"""Convert the Sans spare / kill pictures into CHR tiles (4KB banks 58, 59) and nametable includes.

usage: python py/sans_img.py   (run from the repo root, after the CHR is built)
"""
from PIL import Image

CHR = "Undertale.chr"
OUT = "asm/dodge/sans_img.inc"
DIR = "data/monsters/sans/"
IMAGES = [
    # (name, source, bank, scale)
    ("SANS_SPARE", "sans_spare.png", 58, 1),
    ("SANS_KILL", "sans_bleed_bw.png", 59, 2),
]


def load(src, scale):
    im = Image.open(DIR + src).convert("RGBA")
    bg = Image.new("RGBA", im.size, (0, 0, 0, 255))
    bg.alpha_composite(im)
    im = bg.convert("L").point(lambda v: 255 if v > 110 else 0)
    im = im.crop(im.getbbox())
    if scale != 1:
        im = im.resize((im.width * scale, im.height * scale), Image.NEAREST)
    return im


def tile_bytes(canvas, tx, ty):
    t = canvas.crop((tx * 8, ty * 8, tx * 8 + 8, ty * 8 + 8))
    return bytes(
        sum(1 << (7 - x) for x in range(8) if t.getpixel((x, y))) for y in range(8)
    )


def grid(im, ox, oy):
    canvas = Image.new("L", (256, 240), 0)
    pos_x = (256 - im.width) // 2 // 8 * 8 + ox
    pos_y = oy
    canvas.paste(im, (pos_x, pos_y))
    return canvas


def build(im):
    # try every sub-tile offset near the centre and keep the one with the fewest unique tiles
    best = None
    base_y = (240 - im.height) // 2
    for ox in range(8):
        for dy in range(-4, 4):
            oy = base_y + dy
            if oy < 0 or oy + im.height > 240:
                continue
            canvas = grid(im, ox, oy)
            n = len({tile_bytes(canvas, tx, ty) for ty in range(30) for tx in range(32)})
            if best is None or n < best[0]:
                best = (n, ox, oy)
    canvas = grid(im, best[1], best[2])
    bbox = canvas.getbbox()
    first_row = bbox[1] // 8
    last_row = (bbox[3] - 1) // 8
    rows = [
        [tile_bytes(canvas, tx, ty) for tx in range(32)]
        for ty in range(first_row, last_row + 1)
    ]
    return first_row, rows


def merge(rows):
    """Reduce to 256 tiles (incl. the blank one) by merging the rarest tiles into their nearest neighbour."""
    count = {bytes(8): 1}
    for row in rows:
        for t in row:
            count[t] = count.get(t, 0) + 1
    remap = {}
    while len(count) > 256:
        rare = min((t for t in count if t != bytes(8)), key=lambda t: count[t])
        a = int.from_bytes(rare, "big")
        near = min(
            (t for t in count if t != rare),
            key=lambda t: bin(a ^ int.from_bytes(t, "big")).count("1"),
        )
        count[near] += count.pop(rare)
        remap[rare] = near
        for k, v in list(remap.items()):
            if v == rare:
                remap[k] = near
    return [[remap.get(t, t) for t in row] for row in rows]


chr_data = bytearray(open(CHR, "rb").read())
with open(OUT, "w") as f:
    f.write("; generated by py/sans_img.py\n")
    for name, src, bank, scale in IMAGES:
        first_row, rows = build(load(src, scale))
        rows = merge(rows)
        tiles = [bytes(8)]
        idx = []
        for row in rows:
            out = []
            for t in row:
                if t not in tiles:
                    tiles.append(t)
                out.append(tiles.index(t))
            idx.append(out)
        assert len(tiles) <= 256, len(tiles)
        base = bank * 4096
        chr_data[base:base + 4096] = bytes(4096)
        for i, pat in enumerate(tiles):
            chr_data[base + i * 16:base + i * 16 + 16] = pat + pat
        f.write("%s_ROWS = %d\n" % (name, len(idx)))
        f.write("%s_FIRST_ROW = %d\n" % (name, first_row))
        f.write("%s_nt:\n" % name.lower())
        for row in idx:
            f.write("    .byte " + ", ".join(str(v) for v in row) + "\n")
        print(name, len(tiles), "tiles", len(idx), "rows from", first_row)
open(CHR, "wb").write(chr_data)
